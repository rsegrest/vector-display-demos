#!/usr/bin/env node
// Turns the Hershey .jhf files in packages/demo-kit/data/hershey into packages/demo-kit/src/hersheyData.ts.
//
//   node tools/build-hershey.mjs
//
// A .jhf record is a 5-character glyph number, a 3-character count of coordinate pairs, then the
// pairs themselves; a long record continues on the next line. Each file holds ASCII 32 to 127 in order;
// the last one (127) is not a printable character and is dropped.
// The pairs are kept as they are and decoded when a font is first used (see hersheyFonts.ts).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = join(root, "packages/demo-kit/data/hershey");
const GLYPHS_PER_FONT = 95;

function readGlyphs(file) {
  const text = readFileSync(join(sourceDir, file), "utf8").replace(/\r?\n/g, "");
  const glyphs = [];
  for (let position = 0; position + 8 <= text.length; ) {
    const pairCount = Number.parseInt(text.slice(position + 5, position + 8), 10);
    glyphs.push(text.slice(position + 8, position + 8 + pairCount * 2));
    position += 8 + pairCount * 2;
  }
  if (glyphs.length < GLYPHS_PER_FONT) throw new Error(`${file}: expected ${GLYPHS_PER_FONT} glyphs, found ${glyphs.length}`);
  return glyphs.slice(0, GLYPHS_PER_FONT);
}

const fonts = readdirSync(sourceDir).filter((file) => file.endsWith(".jhf")).sort();
const lines = [
  "// Generated by tools/build-hershey.mjs from packages/demo-kit/data/hershey/*.jhf. Do not edit.",
  "//",
  "// The Hershey Fonts were originally created by Dr. A. V. Hershey while working at",
  "// the U. S. National Bureau of Standards.",
  "",
  "// For each font, the glyphs for ASCII 32 to 126 as Hershey coordinate pairs.",
  "export const HERSHEY_DATA: Readonly<Record<string, readonly string[]>> = {",
  ...fonts.map((file) => `  ${file.replace(".jhf", "")}: ${JSON.stringify(readGlyphs(file))},`),
  "};",
  "",
];
writeFileSync(join(root, "packages/demo-kit/src/hersheyData.ts"), lines.join("\n"));
console.log(`wrote ${fonts.length} fonts`);
